import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { execFileSync } from 'node:child_process';
import {createContentInventory} from './content-scope.mjs';
import {assertCompleteSupportedContent} from '../src/util/content-scope.js';
assertCompleteSupportedContent(await createContentInventory());
const version = process.env.RELEASE_VERSION;
assert.match(version ?? '', /^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?$/);
const manifest = JSON.parse(await readFile('system.json'));
assert.equal(version, manifest.version);
assert.ok(manifest.download.endsWith(`/download/${version}/system.zip`));
const evidencePath = resolve(process.env.INTEGRATION_EVIDENCE ?? '');
assert.ok(relative(resolve('docs/validation'), evidencePath) && !relative(resolve('docs/validation'), evidencePath).startsWith('..'), 'Evidence must be in docs/validation');
const evidence = JSON.parse(await readFile(evidencePath));
assert.equal(evidence.systemVersion, version);
assert.equal(evidence.foundryVersion, manifest.compatibility.verified);
assert.match(evidence.commit ?? '', /^[a-f0-9]{40}$/);
execFileSync('git', ['merge-base', '--is-ancestor', evidence.commit, process.env.GITHUB_SHA]);
const changedRuntime = execFileSync('git', ['diff', '--name-only', evidence.commit, process.env.GITHUB_SHA, '--', 'src', 'static', 'css', 'images', 'packs', 'system.json', 'template.json', 'package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', 'tools', 'docs/data/content-eligibility-review.json', 'docs/data/supported-content-scope.json'], { encoding: 'utf8' }).trim();
assert.equal(changedRuntime, '', 'Runtime/build inputs changed since integration evidence was recorded');
assert.equal(evidence.result, 'passed');
assert.ok(Array.isArray(evidence.scenarios) && ['fresh-install', 'upgrade', 'permissions', 'skills', 'moves', 'variants', 'cancellation', 'duplicate-application'].every(s => evidence.scenarios.some(x => x.id === s && x.result === 'passed')));
const changelog = await readFile('CHANGELOG.md', 'utf8');
const escaped = version.replaceAll('.', '\\.') ;
const entry = changelog.match(new RegExp(`^## ${escaped} - \\d{4}-\\d{2}-\\d{2}\\s*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, 'm'));
assert.ok(entry?.[1]?.trim(), 'A dated version changelog entry is required');
await writeFile('dist/release-notes.md', `${entry[1].trim()}\n\nTested on Foundry ${evidence.foundryVersion}. Evidence: ${process.env.INTEGRATION_EVIDENCE}\n`);
